import re as _re
_PREFIX = _re.compile(r'^(eON_|eOn_|fs_|VPFS_)')

def main():
    import csv, json
    # live board map: entry -> live name (must match seed name before we apply)
    live = {}
    lm = json.load(open('agent/live_functions252.json'))
    for fn in (lm['functions'] if isinstance(lm, dict) else lm):
        a = fn.get('entry') or fn.get('addr') or fn.get('a')
        n = fn.get('name') or fn.get('n')
        if a and n:
            live[a.lower().lstrip('0').rjust(8, '0')] = n
    seen = {}
    with open('seeds/functions.csv', newline='') as f:
        rdr = csv.reader(f)
        hdr = next(rdr)
        assert hdr == ['entry', 'name'], hdr
        for row in rdr:
            if len(row) != 2:
                continue
            ent, nm = row
            ent = ent.strip()
            nm = nm.strip()
            base = nm if nm in SIG else (_PREFIX.sub('', nm) if nm in SIG.get('__sentinel__', ('','')) else None)
            key = nm if nm in SIG else _PREFIX.sub('', nm)
            if key not in SIG:
                continue
            if '[undocumented]' in SIG[key][1]:
                continue  # inferred sigs are out of scope; documented only
            k = ent.lower().lstrip('0').rjust(8, '0')
            if k not in live:
                continue
            if live[k] != nm:
                continue  # seed/board drift on this row; skip, do not apply
            if ent not in seen:
                seen[ent] = key
    out = []
    for ent in sorted(seen):
        ret, proto = SIG[seen[ent]]
        out.append({'entry': ent, 'name': seen[ent], 'ret': ret, 'proto': proto})
    print(f'w260 targets (canonical exact spellings): {len(out)}')
    from collections import Counter
    c = Counter(r['ret'] for r in out)
    print('return-type histogram:', dict(c))
    with open('/tmp/w260_targets.tsv', 'w') as f:
        for r in out:
            f.write(f"{r['entry']}\t{r['name']}\t{r['ret']}\t{r['proto']}\n")

if __name__ == '__main__':
    main()
